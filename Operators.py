# arithmetic operators
a = 10
b = 5

print(a+b) # addition
print(a-b) # subtraction
print(a*b) # multiplication
print(a/b) # division
print(a%b) # modulo for calculating remainder
print(a**b) # calculating power

# relational operators

print(a < b)
print(a > b)
print(a != b)
print(a == b)
print(a >= b)
print(a <= b)

# Assignment Operators

a += 1
print(a)

a -= 2
print(a)

a *= 1
print(a)

a /= 1
print(a)

# logical operators

var = False

print(not var) # Not operator

print((5 > 3) and (8 > 9)) # And operator

print((5 > 3) or (8 > 7)) # or operator

ans1 = int(5 + 10.0) # type casting

